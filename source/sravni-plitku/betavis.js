/* ================================================================
   ZOOM — обычный (встроенный) рендер
================================================================ */
function applyInlineTransform() {
  const scene = $id('renderScene');
  const wrap = scene ? scene.parentElement : null; // .render-wrapper
  if (!scene) return;
  // Ограничиваем сдвиг границами кадра
  const maxX = wrap ? (S.inlineZoom - 1) * wrap.clientWidth  / 2 : 0;
  const maxY = wrap ? (S.inlineZoom - 1) * wrap.clientHeight / 2 : 0;
  S.inlinePanX = Math.max(-maxX, Math.min(maxX, S.inlinePanX));
  S.inlinePanY = Math.max(-maxY, Math.min(maxY, S.inlinePanY));
  scene.style.transformOrigin = 'center center';
  scene.style.transform = `translate(${S.inlinePanX}px, ${S.inlinePanY}px) scale(${S.inlineZoom})`;
  if (wrap) wrap.classList.toggle('pannable', S.inlineZoom > 1);
}
function inlineZoomBy(delta) {
  const next = Math.min(INLINE_ZOOM_MAX, Math.max(ZOOM_MIN, +(S.inlineZoom + delta).toFixed(2)));
  if (next === S.inlineZoom) return;
  S.inlineZoom = next;
  if (S.inlineZoom === 1) { S.inlinePanX = 0; S.inlinePanY = 0; } // 1:1 — сбрасываем сдвиг
  applyInlineTransform();
}

// Перетаскивание приближённого обычного рендера (инструмент «рука»).
// Отличаем перетаскивание от клика по зоне: клик подавляется только если был сдвиг.
function bindInlinePan() {
  const wrap = $qs('.render-wrapper');
  if (!wrap) return;
  let down = false, dragging = false, startX = 0, startY = 0, baseX = 0, baseY = 0, pid = null;

  wrap.addEventListener('pointerdown', e => {
    if (S.inlineZoom <= 1 || e.button !== 0) return;
    // не перехватываем нажатия на кнопках поверх рендера
    if (e.target.closest('button')) return;
    down = true; dragging = false;
    startX = e.clientX; startY = e.clientY;
    baseX = S.inlinePanX; baseY = S.inlinePanY; pid = e.pointerId;
  });
  wrap.addEventListener('pointermove', e => {
    if (!down) return;
    const dx = e.clientX - startX, dy = e.clientY - startY;
    if (!dragging && Math.hypot(dx, dy) > 4) {
      dragging = true;
      wrap.classList.add('panning');
      try { wrap.setPointerCapture(pid); } catch (_) {}
    }
    if (dragging) { S.inlinePanX = baseX + dx; S.inlinePanY = baseY + dy; applyInlineTransform(); }
  });
  const end = () => {
    if (!down) return;
    down = false;
    if (dragging) {
      wrap.classList.add('just-dragged'); // подавить следующий клик
      setTimeout(() => wrap.classList.remove('just-dragged'), 0);
    }
    dragging = false;
    wrap.classList.remove('panning');
    try { wrap.releasePointerCapture(pid); } catch (_) {}
  };
  wrap.addEventListener('pointerup', end);
  wrap.addEventListener('pointercancel', end);
  // Не даём начинаться выделению текста подписей при перетаскивании
  wrap.addEventListener('selectstart', e => { if (S.inlineZoom > 1) e.preventDefault(); });
  wrap.addEventListener('dragstart', e => e.preventDefault());
  // Клик после перетаскивания не должен выбирать зону
  wrap.addEventListener('click', e => {
    if (wrap.classList.contains('just-dragged')) { e.stopPropagation(); e.preventDefault(); }
  }, true);
}

