function resetAll() {
  Object.keys(S.assignments).forEach(k => {
    if (k.startsWith(S.roomId + '.')) delete S.assignments[k];
  });
  S.zoneId = null;
  markServiceDirty();
  S.loadToken++;            // отменяем незавершённые загрузки
  S.loadingZones = new Set();
  renderScene();
  renderCatalog();
  updateZoneBadge();
  updateHint();
  trackEvent('reset_scene', { scene_id: S.roomId });
  toast('Интерьер сброшен');
}

