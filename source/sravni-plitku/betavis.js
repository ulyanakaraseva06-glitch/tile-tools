/* ================================================================
   EXPORT — формирование единого JPG (через модуль export-image.js)
================================================================ */
async function onExport() {
  if (!global_TileExport()) { toast('Модуль экспорта не загружен'); return; }
  if (!roomData(S.roomId)) { toast('Экспорт доступен для размеченного интерьера'); return; }

  trackEvent('download_click', { scene_id: S.roomId, selection: getCurrentSelection() });

  // --- ЭТАП 05: учёт скачивания ОБЯЗАТЕЛЕН и БЛОКИРУЮЩИЙ ---
  // Без подтверждённого ok от log_download.php файл не генерируем
  // (нельзя позволить скачать в обход лимита, если API недоступен).
  if (!(window.SP_USER && window.SP_USER.id)) {
    toast('Войдите, чтобы скачать изображение');
    return;
  }

  const selection = getCurrentSelection();
  const sessionKey = (window.SP_ANALYTICS && window.SP_ANALYTICS.sessionKey) || null;
  let downloadEventId = null;

  try {
    const resp = await fetch('auth/api/log_download.php', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        csrf:         window.SP_USER.csrf,
        sessionKey:   sessionKey,
        sceneId:      S.roomId,
        selection:    selection,
        exportFormat: 'jpg'
      })
    });
    const data = await resp.json();
    if (!data.ok) {
      if (data.reason === 'limit')                                  toast(`Достигнут месячный лимит скачиваний (${data.limit})`);
      else if (data.reason === 'auth' || data.reason === 'access')  toast('Сессия истекла — войдите снова');
      else                                                          toast('Не удалось зарегистрировать скачивание');
      return; // лимит/ошибка — НЕ генерируем
    }
    downloadEventId = data.downloadEventId || null;
  } catch (e) {
    // API недоступен — по коммерческому правилу скачивание блокируется
    console.warn('log_download недоступен', e);
    toast('Сервис скачивания недоступен, попробуйте позже');
    return;
  }

  // Подтверждение результата генерации на сервере (best-effort).
  const confirmDownload = (status, errorMessage) => {
    if (!downloadEventId) return;
    try {
      fetch('auth/api/confirm_download.php', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          csrf: window.SP_USER.csrf,
          downloadEventId: downloadEventId,
          status: status,
          errorMessage: errorMessage || null
        }),
        keepalive: true
      }).catch(function () {});
    } catch (e) {}
  };

  // Собираем применённые плитки с настоящими рендерами по зонам
  const renders = {};
  const textures = {};
  roomZones(S.roomId).forEach(z => {
    const tid = S.assignments[assignKey(S.roomId, z.id)];
    const tile = tid ? TILES_DB.find(t => t.id === tid) : null;
    const rImg = renderForRoom(tile, S.roomId);
    if (tile && tile.hasRealImg && rImg) {
      renders[z.id] = `${DOMAIN}${rImg}`;
    } else if (tile && tileFaces(tile).length) {
      textures[z.id] = { sources: tileFaces(tile).map(src => `${DOMAIN}${src}`), aspect: tileAspect(tile) };
    }
  });

  const btn = $id('btnExport');
  btn.classList.add('is-busy');
  toast('Формирую изображение…');
  try {
    const _ts = tempStyle(S.lightTemp);
    await window.TileExport.generate({
      baseSrc:  roomBase(S.roomId),
      viewBox:  roomData(S.roomId).viewBox,
      paths:    roomPaths(S.roomId),
      order:    roomZones(S.roomId).map(z => z.id),
      renders,
      textures,
      quality:  1,
      filename: 'sravni-plitku.jpg',
      lightTempColor: _ts.color,   // тот же цвет/альфа, что и в превью
      lightTempAlpha: _ts.alpha,
      exposureFilter: exposureFilter(S.exposure), // паритет экспозиции с превью
    });
    toast('Готово — изображение сохранено');
    if (window.parent !== window) {
      const roomTitle = (ROOMS.find(room => room.id === S.roomId) || {}).name || 'Интерьер';
      window.parent.postMessage({
        type: 'tile-tools:project-saved',
        project: {
          id: activeVisualizationProjectId(),
          type: 'visualization',
          title: `Визуализация — ${roomTitle}`,
          status: 'active',
          updatedAt: new Date().toISOString(),
          metric: `${Object.keys(selection).length} выбранных зон`,
          payload: { roomId: S.roomId, selection, lightTemp: S.lightTemp, exposure: S.exposure }
        }
      }, '*');
    }
    confirmDownload('success');
    trackEvent('download_success', { scene_id: S.roomId, selection: selection });
  } catch (e) {
    console.error(e);
    toast('Не удалось сформировать изображение');
    const errText = String(e && e.message || e);
    confirmDownload('failed', errText);
    trackEvent('download_failed', { scene_id: S.roomId, metadata: { error: errText } });
  } finally {
    btn.classList.remove('is-busy');
  }
}
function global_TileExport() {
  return window.TileExport && typeof window.TileExport.generate === 'function';
}

