/* Горизонтальная прокрутка шапки на узких экранах: затухания у краёв,
   прокрутка колесом и одноразовый «кивок»-намёк, что контент крутится. */
function setupHeaderScroll() {
  const sc = $id('headerScroll');
  const hdr = $id('appHeader');
  if (!sc || !hdr) return;
  const hasOverflow = () => (sc.scrollWidth - sc.clientWidth) > 4;
  const update = () => {
    hdr.classList.toggle('has-overflow', hasOverflow());
    hdr.classList.toggle('at-start', sc.scrollLeft <= 2);
    hdr.classList.toggle('at-end', sc.scrollLeft + sc.clientWidth >= sc.scrollWidth - 2);
  };
  sc.addEventListener('scroll', update, { passive: true });
  window.addEventListener('resize', update);
  sc.addEventListener('wheel', e => {
    if (!hasOverflow()) return;
    if (Math.abs(e.deltaY) > Math.abs(e.deltaX)) { sc.scrollLeft += e.deltaY; e.preventDefault(); }
  }, { passive: false });
  update();
  if (hasOverflow()) {                       // намёк: чуть проматываем и возвращаем
    setTimeout(() => {
      sc.scrollTo({ left: 40, behavior: 'smooth' });
      setTimeout(() => sc.scrollTo({ left: 0, behavior: 'smooth' }), 720);
    }, 550);
  }
}

