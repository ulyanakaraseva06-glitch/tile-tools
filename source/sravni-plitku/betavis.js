function getGridDimensions() {
  const panel = document.querySelector('.catalog-panel');
  if (!panel) return { cols: 4, rows: 3 };
  const panelW = panel.clientWidth - 32; // minus horizontal padding
  // Reserve vertical space for: tabs, search, filters, meta row, pagination, gaps
  const reservedH = 44 + 42 + 80 + 32 + 52 + 30;
  const panelH = Math.max(200, panel.clientHeight - reservedH);

  const minCardW = 90;
  const cols = Math.max(3, Math.min(4, Math.floor(panelW / minCardW)));
  const cardW = Math.floor((panelW - (cols - 1) * 7) / cols);
  // Full card height = square image (cardW) + label block (~38) + gap (7)
  const cardH = cardW + 38 + 7;
  const rows = Math.max(3, Math.floor(panelH / cardH));

  return { cols, rows };
}

