// Применить плитку к КОНКРЕТНОЙ зоне (используется и из попапа, где зону
// можно выбрать прямо там, не выделяя её заранее на рендере).
function applyTileToZone(tid, zoneId) {
  if (!zoneId) return;
  const key = assignKey(S.roomId, zoneId);
  if (S.assignments[key] === tid) {
    // Плитка уже применена к этой зоне — повторно ничего не убираем.
    // Сброс возможен только целиком, кнопкой «Сбросить зоны».
    return;
  }
  const tile = TILES_DB.find(t => t.id === tid);
  const _rImg = renderForRoom(tile, S.roomId);

  // Для настоящих рендеров: показываем анимацию на участке, подгружаем новое
  // изображение в фоне и подменяем его только когда оно полностью готово —
  // старая плитка при этом не пропадает, «пустого» кадра не возникает.
  if (tile && tile.hasRealImg && _rImg) {
    const token = ++S.loadToken;
    S.loadingZones = new Set([zoneId]);
    renderScene();              // показывает старую плитку + анимацию загрузки

    let done = false;
    const commit = () => {
      if (done || token !== S.loadToken) return;   // уже выполнено или выбрали другое
      done = true;
      S.loadingZones.delete(zoneId);
      S.assignments[key] = tid;
      markServiceDirty();
      renderScene();
      renderCatalog();
      trackEvent('tile_apply', Object.assign(
        { scene_id: S.roomId, zone_id: zoneId, selection: getCurrentSelection() },
        tileMeta(tid)));
      toast(`Применено: ${tile.shortName || tile.name}`);
    };
    const img = new Image();
    img.onload = commit;
    img.onerror = commit;       // даже при ошибке завершаем (покажется запасной вариант)
    img.src = `${DOMAIN}${_rImg}`;
    if (img.complete) commit(); // изображение уже в кэше
    return;
  }

  // Плитки без настоящего рендера — мгновенно
  S.assignments[key] = tid;
  markServiceDirty();
  trackEvent('tile_apply', Object.assign(
    { scene_id: S.roomId, zone_id: zoneId, selection: getCurrentSelection() },
    tileMeta(tid)));
  toast(`Применено: ${tile?.shortName || tile?.name}`);
  renderScene();
  renderCatalog();
}

