function getFilteredTiles() {
  let pool = S.tab === 'favorites'
    ? TILES_DB.filter(t => S.favorites.has(favKey(t.id)))
    : TILES_DB;

  return pool.filter(t => {
    // Пустой массив фильтра = ограничения нет (все значения)
    // Пустой массив фильтра у пользователя = ограничения нет (все значения).
    // Плитка проходит, если есть пересечение; плитка без значений по активному фильтру — отсеивается.
    if (S.filters.color.length   && !S.filters.color.some(v => (t.color||[]).includes(v)))     return false;
    if (S.filters.size.length    && !S.filters.size.some(v => (t.size||[]).includes(v)))       return false;
    if (S.filters.surface.length && !S.filters.surface.some(v => (t.surface||[]).includes(v))) return false;
    if (S.filters.design.length  && !S.filters.design.some(v => (t.design||[]).includes(v)))   return false;
    if (S.query) {
      const q = S.query.toLowerCase();
      return (t.name||'').toLowerCase().includes(q)
          || (t.brand||'').toLowerCase().includes(q)
          || (t.collection||'').toLowerCase().includes(q);
    }
    return true;
  }).sort((a, b) => Number(S.favorites.has(favKey(b.id))) - Number(S.favorites.has(favKey(a.id))));
}

