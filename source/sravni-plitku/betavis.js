function bindEvents() {

  // Освещение (температура): шкала в шапке + кнопка-лампочка = сброс к нейтрали
  const _ls = $id('lightSlider');
  if (_ls) _ls.addEventListener('input', e => setLightTemp(e.target.value / 100));
  const _lreset = $id('btnLightReset');
  if (_lreset) _lreset.addEventListener('click', resetLightTemp);
  const _es = $id('expSlider');
  if (_es) _es.addEventListener('input', e => setExposure(e.target.value / 100));
  const _ereset = $id('btnExpReset');
  if (_ereset) _ereset.addEventListener('click', resetExposure);

  // Tile grid clicks (delegated)
  $id('tileGrid').addEventListener('click', e => {
    const applyCardBtn = e.target.closest('[data-apply-all-card]');
    if (applyCardBtn) { e.stopPropagation(); applyTileToAllZones(applyCardBtn.dataset.applyAllCard); return; }

    const infoBtn = e.target.closest('[data-info]');
    if (infoBtn) { e.stopPropagation(); showTileInfoPopup(infoBtn.dataset.info); return; }

    const favBtn = e.target.closest('[data-fav]');
    if (favBtn) { e.stopPropagation(); toggleFavorite(favBtn.dataset.fav); return; }

    const card = e.target.closest('[data-tid]');
    if (card) selectTile(card.dataset.tid);
  });

  // Search
  $id('searchInput').addEventListener('input', e => {
    S.query = e.target.value.trim();
    S.page = 1;
    renderCatalog();
    if (S.query) trackEventDebounced('search', { search_query: S.query });
  });

  // Filter dropdowns
  document.addEventListener('click', e => {
    const opt = e.target.closest('.filter-option');
    if (opt) {
      const key = opt.dataset.filter;
      const val = opt.dataset.val;
      const sel = S.filters[key];
      if (val === '__all__') {
        S.filters[key] = [];           // «Все значения» → снять ограничения
      } else {
        const i = sel.indexOf(val);
        if (i === -1) sel.push(val); else sel.splice(i, 1); // переключаем значение
      }
      S.page = 1;
      updateDropdownLabels();
      renderCatalog();
      trackEventDebounced('filter_change', { filters: S.filters });
      // меню НЕ закрываем — можно отметить сразу несколько значений
      return;
    }
    const dd = e.target.closest('.filter-dropdown');
    if (dd) {
      const isOpen = dd.classList.contains('open');
      closeAllDropdowns();
      if (!isOpen) dd.classList.add('open');
      return;
    }
    closeAllDropdowns();
  });

  // Clear filters
  $id('clearFilters').addEventListener('click', () => {
    Object.keys(S.filters).forEach(k => S.filters[k] = []);
    S.query = '';
    S.page = 1;
    $id('searchInput').value = '';
    updateDropdownLabels();
    renderCatalog();
  });

  // Header & render buttons
  $id('btnReset').addEventListener('click', resetAll);
  const _howto = $id('btnHowto');
  if (_howto) _howto.addEventListener('click', openHowto);
  setupHeaderScroll();
  $id('btnExport').addEventListener('click', onExport);
  $id('btnUser').addEventListener('click', () => {
    if (window.SP_USER && window.SP_USER.id) {
      window.location.href = 'auth/cabinet.php';
    } else {
      window.location.href = 'auth/login.php';
    }
  });

  // Tabs in catalog panel
  $qsa('.catalog-tab').forEach(btn => {
    btn.addEventListener('click', () => setTab(btn.dataset.tab));
  });

  // Popup close
  $id('popupClose').addEventListener('click', closePopup);
  $id('popupOverlay').addEventListener('click', e => { if (e.target===$id('popupOverlay')) closePopup(); });

  // Делегированная обработка кнопок внутри инфо-попапа плитки
  $id('popupContent').addEventListener('click', e => {
    const favBtn = e.target.closest('[data-fav-popup]');
    if (favBtn) {
      const tid = favBtn.dataset.favPopup;
      toggleFavorite(tid);                       // переключаем + сохраняем + обновляем каталог
      const nowFav = S.favorites.has(favKey(tid));
      favBtn.classList.toggle('popup-action-btn--active', nowFav);
      favBtn.innerHTML = `<svg width="14" height="14" viewBox="0 0 24 24" fill="${nowFav?'currentColor':'none'}" stroke="currentColor" stroke-width="2">
          <path d="M20.84 4.61a5.5 5.5 0 0 0-7.78 0L12 5.67l-1.06-1.06a5.5 5.5 0 0 0-7.78 7.78l1.06 1.06L12 21.23l7.78-7.78 1.06-1.06a5.5 5.5 0 0 0 0-7.78z"/>
        </svg>${nowFav ? 'В избранном' : 'В избранное'}`;
      return;                                     // попап НЕ закрываем
    }
    const applyAll = e.target.closest('[data-apply-all]');
    if (applyAll) {
      applyTileToAllZones(applyAll.dataset.applyAll);
      // попап НЕ закрываем — по требованию
      return;
    }
  });

  // Zoom (обычный рендер) / Fullscreen
  $id('btnZoomIn').addEventListener('click', () => inlineZoomBy(ZOOM_STEP));
  $id('btnZoomOut').addEventListener('click', () => inlineZoomBy(-ZOOM_STEP));
  bindInlinePan();
  $id('btnFullscreen').addEventListener('click', openFullscreen);

  // Fullscreen modal controls
  $id('fsClose').addEventListener('click', closeFullscreen);
  $id('fsExit').addEventListener('click', closeFullscreen);
  $id('fsZoomIn').addEventListener('click', () => fsZoomBy(ZOOM_STEP));
  $id('fsZoomOut').addEventListener('click', () => fsZoomBy(-ZOOM_STEP));
  bindFsPan();
  // Клик по пустому месту НЕ закрывает (закрытие только кнопкой)

  // Keyboard
  document.addEventListener('keydown', e => {
    if (e.key==='Escape') {
      if ($id('fsOverlay').classList.contains('open')) { closeFullscreen(); return; }
      if ($id('popupOverlay').classList.contains('open')) { closePopup(); return; }
      if (S.zoneId) { S.zoneId = null; renderScene(); updateZoneBadge(); updateHint(); }
    }
  });

  // Resize → re-render catalog layout
  let resizeTimer;
  window.addEventListener('resize', () => {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(() => renderCatalog(), 150);
  });
}

