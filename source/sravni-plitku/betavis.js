/* ================================================================
   SMART PAGINATION
================================================================ */
function renderPagination(total, totalPages) {
  const pg = $id('pagination');
  if (totalPages <= 1) { pg.innerHTML = ''; return; }

  const p = S.page;
  // Pages to show: first, last, current ± 1
  const shown = new Set([1, totalPages, p, p-1, p+1].filter(x => x >= 1 && x <= totalPages));
  const sorted = [...shown].sort((a,b)=>a-b);

  let html = `<button class="page-btn page-arrow ${p===1?'disabled':''}" data-pg="${p-1}">
    <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><polyline points="15 18 9 12 15 6"/></svg>
  </button>`;

  let prev = 0;
  sorted.forEach(n => {
    if (n - prev > 1) html += `<span class="page-btn page-ellipsis">…</span>`;
    html += `<button class="page-btn ${n===p?'active':''}" data-pg="${n}">${n}</button>`;
    prev = n;
  });

  html += `<button class="page-btn page-arrow ${p===totalPages?'disabled':''}" data-pg="${p+1}">
    <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><polyline points="9 18 15 12 9 6"/></svg>
  </button>`;

  pg.innerHTML = html;

  pg.querySelectorAll('[data-pg]').forEach(btn => {
    btn.addEventListener('click', () => {
      const pg = parseInt(btn.dataset.pg);
      if (!isNaN(pg) && pg >= 1 && pg <= totalPages) {
        S.page = pg;
        renderCatalog();
        $id('tileGrid').scrollTop = 0;   // новая страница — показываем сверху
      }
    });
  });
}

